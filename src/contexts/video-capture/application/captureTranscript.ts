import {
  isUsableTranscript,
  mergeIntoLines,
  parseManualTranscript,
  type TimedLine,
  type Transcript,
  type TranscriptSource,
} from '../domain'

/**
 * One way of obtaining a transcript. YouTube breaks each of these from time to
 * time, so they are tried in order behind this port and the use case never
 * knows how a given one works.
 */
export interface TranscriptProvider {
  readonly name: TranscriptSource
  get(videoId: string, opts: { preferredLangs: readonly string[] }): Promise<Transcript | null>
}

export interface TranscriptCache {
  get(videoId: string): Promise<Transcript | null>
  put(transcript: Transcript): Promise<void>
}

export type CaptureAttempt = {
  provider: TranscriptSource | 'cache'
  outcome: 'ok' | 'empty' | 'error'
  message?: string
}

export type CaptureResult = {
  transcript: Transcript | null
  fromCache: boolean
  /** Which providers were tried and how each went — shown in the UI on failure. */
  attempts: CaptureAttempt[]
}

export type CaptureTranscriptInput = {
  videoId: string
  preferredLangs?: readonly string[]
  /** Skip the cache read (the result is still written back). */
  force?: boolean
}

export type CaptureTranscriptDeps = {
  providers: readonly TranscriptProvider[]
  cache?: TranscriptCache
}

/**
 * Cache first, then each provider in order; the first usable transcript wins.
 * A provider that throws is recorded and skipped — it must never stop the next
 * one from being tried.
 */
export async function captureTranscript(
  input: CaptureTranscriptInput,
  deps: CaptureTranscriptDeps,
): Promise<CaptureResult> {
  const attempts: CaptureAttempt[] = []
  const preferredLangs = input.preferredLangs ?? []

  if (deps.cache && !input.force) {
    try {
      const cached = await deps.cache.get(input.videoId)
      if (isUsableTranscript(cached)) {
        attempts.push({ provider: 'cache', outcome: 'ok' })
        return { transcript: cached, fromCache: true, attempts }
      }
    } catch (err) {
      attempts.push({ provider: 'cache', outcome: 'error', message: errorMessage(err) })
    }
  }

  for (const provider of deps.providers) {
    try {
      const t = await provider.get(input.videoId, { preferredLangs })
      if (isUsableTranscript(t) && t.videoId === input.videoId) {
        attempts.push({ provider: provider.name, outcome: 'ok' })
        if (deps.cache) await deps.cache.put(t).catch(() => {})
        return { transcript: t, fromCache: false, attempts }
      }
      attempts.push({ provider: provider.name, outcome: 'empty' })
    } catch (err) {
      attempts.push({ provider: provider.name, outcome: 'error', message: errorMessage(err) })
    }
  }

  return { transcript: null, fromCache: false, attempts }
}

/**
 * Transcript → the lines the concept pipeline consumes. This is the boundary
 * between the two contexts: concept-mapping only ever sees `TimedLine`s.
 */
export function transcriptToLines(t: Transcript): TimedLine[] {
  if (!t.timed) {
    // Untimed paste: keep paragraphs as-is so the LLM still sees structure.
    return t.segments.map((s) => ({ start: 0, text: s.text }))
  }
  return mergeIntoLines(t.segments)
}

/**
 * Last-resort path: the user pasted the transcript themselves (copied from
 * YouTube's panel, or any text). Null when there is nothing usable in it.
 */
export function manualTranscript(videoId: string, text: string, lang = 'und'): Transcript | null {
  const { segments, timed } = parseManualTranscript(text)
  const t: Transcript = { videoId, lang, autoGenerated: false, timed, source: 'manual', segments }
  return isUsableTranscript(t) ? t : null
}

function errorMessage(err: unknown): string {
  return err instanceof Error ? err.message : String(err)
}
