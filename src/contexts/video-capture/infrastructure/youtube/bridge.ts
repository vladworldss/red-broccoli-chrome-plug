/**
 * Runs in the ISOLATED world (see src/contents/youtube-bridge.ts). It is the
 * only part of the extension the side panel talks to on the page:
 *
 *  - collects timedtext bodies the MAIN-world hooks intercepted, per video
 *  - answers the panel's GET_STATE / GET_TRANSCRIPT / SEEK requests
 *  - announces SPA navigations (`yt-navigate-finish`) as SH_VIDEO_CHANGED
 */
import {
  chooseCaptionTrack,
  parseTimedTextBody,
  timedTextUrlInfo,
  videoIdFromUrl,
} from '../../domain/parsers'
import type { Segment, Transcript, VideoMeta } from '../../domain/Transcript'
import {
  PAGE_FROM_BRIDGE,
  PAGE_FROM_MAIN,
  isTabRequest,
  type BridgeToMain,
  type CaptureMode,
  type SeekResponse,
  type TabState,
  type TranscriptResponse,
  type VideoChangedEvent,
} from '../messages'
import { VIDEO_ELEMENT } from './selectors'
import { scrapeTranscriptPanel } from './transcriptPanel'

type Capture = { lang: string; autoGenerated: boolean; segments: Segment[] }

const META_TIMEOUT_MS = 1500
const CAPTURE_TIMEOUT_MS = 8000
/** Keep captures for a handful of recent videos only — this is page memory. */
const MAX_VIDEOS = 5

export function startBridge(win: Window = window): void {
  const captures = new Map<string, Capture[]>()
  const pending = new Map<string, (data: unknown) => void>()
  const captureWaiters = new Set<() => void>()

  // --- page hop --------------------------------------------------------------
  win.addEventListener('message', (event: MessageEvent) => {
    if (event.source !== win) return
    const msg = event.data as Record<string, unknown> | null
    if (!msg || msg.source !== PAGE_FROM_MAIN) return

    if (msg.kind === 'timedtext' && typeof msg.url === 'string' && typeof msg.body === 'string') {
      const info = timedTextUrlInfo(msg.url)
      if (!info) return
      const videoId = info.videoId ?? videoIdFromUrl(win.location.href)
      const segments = parseTimedTextBody(msg.body)
      if (!videoId || segments.length === 0) return
      storeCapture(captures, videoId, { lang: info.lang, autoGenerated: info.autoGenerated, segments })
      for (const w of [...captureWaiters]) w()
      return
    }
    if ((msg.kind === 'meta' || msg.kind === 'captions') && typeof msg.requestId === 'string') {
      pending.get(msg.requestId)?.(msg)
      pending.delete(msg.requestId)
    }
  })

  const toMain = (msg: BridgeToMain) => win.postMessage(msg, win.location.origin)

  const askMain = <T>(build: (requestId: string) => BridgeToMain, timeoutMs: number): Promise<T | null> =>
    new Promise((resolve) => {
      const requestId = `${Date.now().toString(36)}-${Math.random().toString(36).slice(2)}`
      const timer = setTimeout(() => {
        pending.delete(requestId)
        resolve(null)
      }, timeoutMs)
      pending.set(requestId, (data) => {
        clearTimeout(timer)
        resolve(data as T)
      })
      toMain(build(requestId))
    })

  const requestMeta = async (): Promise<VideoMeta | null> => {
    const res = await askMain<{ meta?: VideoMeta | null }>(
      (requestId) => ({ source: PAGE_FROM_BRIDGE, kind: 'get-meta', requestId }),
      META_TIMEOUT_MS,
    )
    return res?.meta ?? null
  }

  const waitForCapture = (videoId: string, timeoutMs: number): Promise<boolean> =>
    new Promise((resolve) => {
      if (captures.get(videoId)?.length) return resolve(true)
      const done = (ok: boolean) => {
        clearTimeout(timer)
        captureWaiters.delete(check)
        resolve(ok)
      }
      const check = () => {
        if (captures.get(videoId)?.length) done(true)
      }
      const timer = setTimeout(() => done(false), timeoutMs)
      captureWaiters.add(check)
    })

  // --- capture strategies ---------------------------------------------------
  const intercept = async (videoId: string, preferredLangs: string[]): Promise<Transcript | null> => {
    const meta = await requestMeta()
    const tracks = meta?.videoId === videoId ? meta.captionTracks : []
    if (meta?.videoId === videoId && tracks.length === 0) return null // video has no captions at all

    const track = chooseCaptionTrack(tracks, preferredLangs)
    const pick = () => pickCapture(captures.get(videoId) ?? [], track?.languageCode ?? null)

    let cap = pick()
    if (!cap) {
      await askMain<{ ok: boolean }>(
        (requestId) => ({
          source: PAGE_FROM_BRIDGE,
          kind: 'enable-captions',
          requestId,
          languageCode: track?.languageCode ?? null,
        }),
        META_TIMEOUT_MS,
      )
      await waitForCapture(videoId, CAPTURE_TIMEOUT_MS)
      toMain({ source: PAGE_FROM_BRIDGE, kind: 'restore-captions' })
      cap = pick()
    }
    if (!cap) return null
    return {
      videoId,
      lang: cap.lang,
      autoGenerated: cap.autoGenerated,
      timed: true,
      source: 'intercept',
      segments: cap.segments,
    }
  }

  const dom = async (videoId: string, preferredLangs: string[]): Promise<Transcript | null> => {
    if (videoIdFromUrl(win.location.href) !== videoId) return null
    const segments = await scrapeTranscriptPanel(win.document)
    if (segments.length === 0) return null
    const meta = await requestMeta()
    // The panel shows the default track; its language isn't in the DOM, so
    // the best guess is the track the player would pick.
    const track = meta?.videoId === videoId ? chooseCaptionTrack(meta.captionTracks, preferredLangs) : null
    return {
      videoId,
      lang: track?.languageCode ?? 'und',
      autoGenerated: track?.autoGenerated ?? false,
      timed: true,
      source: 'dom',
      segments,
    }
  }

  const getTranscript = async (
    videoId: string,
    mode: CaptureMode,
    preferredLangs: string[],
  ): Promise<TranscriptResponse> => {
    try {
      const transcript =
        mode === 'intercept' ? await intercept(videoId, preferredLangs) : await dom(videoId, preferredLangs)
      return { ok: true, transcript }
    } catch (err) {
      return { ok: false, error: err instanceof Error ? err.message : String(err) }
    }
  }

  const getState = async (): Promise<TabState> => {
    const videoId = videoIdFromUrl(win.location.href)
    const meta = videoId ? await requestMeta() : null
    return {
      videoId,
      title: win.document.title.replace(/\s*-\s*YouTube\s*$/, '').replace(/^\(\d+\)\s*/, ''),
      meta: meta && meta.videoId === videoId ? meta : null,
    }
  }

  const seek = (t: number): SeekResponse => {
    for (const sel of VIDEO_ELEMENT) {
      const video = win.document.querySelector<HTMLVideoElement>(sel)
      if (video) {
        video.currentTime = Math.max(0, t)
        return { ok: true }
      }
    }
    return { ok: false }
  }

  // --- extension hop ----------------------------------------------------------
  chrome.runtime.onMessage.addListener((msg: unknown, _sender, sendResponse) => {
    if (!isTabRequest(msg)) return false
    if (msg.type === 'SH_SEEK') {
      sendResponse(seek(msg.t))
      return false
    }
    const work =
      msg.type === 'SH_GET_STATE' ? getState() : getTranscript(msg.videoId, msg.mode, msg.preferredLangs)
    work.then(sendResponse, () => sendResponse(null))
    return true // keep the channel open for the async answer
  })

  // --- navigation -------------------------------------------------------------
  let announced: string | null | undefined
  const announce = () => {
    const videoId = videoIdFromUrl(win.location.href)
    if (videoId === announced) return
    announced = videoId
    const event: VideoChangedEvent = { type: 'SH_VIDEO_CHANGED', videoId }
    // Rejects with "Receiving end does not exist" when no panel is open.
    chrome.runtime.sendMessage(event).catch(() => {})
  }
  win.document.addEventListener('yt-navigate-finish', announce)
  win.addEventListener('popstate', announce)
  announce()
}

function storeCapture(captures: Map<string, Capture[]>, videoId: string, cap: Capture): void {
  const list = (captures.get(videoId) ?? []).filter((c) => c.lang !== cap.lang)
  list.push(cap)
  captures.delete(videoId) // re-insert → most recent last
  captures.set(videoId, list)
  while (captures.size > MAX_VIDEOS) {
    const oldest = captures.keys().next().value
    if (oldest === undefined) break
    captures.delete(oldest)
  }
}

function pickCapture(list: readonly Capture[], lang: string | null): Capture | null {
  if (list.length === 0) return null
  if (lang) {
    const exact = list.find((c) => c.lang === lang)
    if (exact) return exact
  }
  return list[list.length - 1] ?? null
}
