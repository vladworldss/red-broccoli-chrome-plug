/**
 * Pure parsers for every shape a YouTube transcript can arrive in.
 *
 * No DOMParser, no `document` — XML is handled with regexes so the domain stays
 * runnable in a worker or under plain vitest. The inputs are machine-generated
 * and flat (no nesting beyond <p><s>), which keeps that safe.
 */
import { parseTimestamp } from '../../../shared/time'
import type { CaptionTrack, Chapter, Segment, VideoMeta } from './Transcript'

const VIDEO_ID = /^[A-Za-z0-9_-]{11}$/

/** Accepts watch?v=, youtu.be/, /shorts/, /live/, /embed/. Null otherwise. */
export function videoIdFromUrl(url: string): string | null {
  let u: URL
  try {
    u = new URL(url)
  } catch {
    return null
  }
  const host = u.hostname.replace(/^www\.|^m\./, '')
  let candidate: string | null = null
  if (host === 'youtu.be') {
    candidate = u.pathname.slice(1).split('/')[0] ?? null
  } else if (host === 'youtube.com' || host === 'youtube-nocookie.com') {
    if (u.pathname === '/watch') candidate = u.searchParams.get('v')
    else {
      const m = /^\/(?:shorts|live|embed)\/([^/?#]+)/.exec(u.pathname)
      candidate = m?.[1] ?? null
    }
  }
  return candidate && VIDEO_ID.test(candidate) ? candidate : null
}

/**
 * What a /api/timedtext URL says about the track it fetches. `tlang` (an
 * auto-translated track) wins over `lang`, since that is the text we receive.
 */
export function timedTextUrlInfo(
  url: string,
): { videoId: string | null; lang: string; autoGenerated: boolean } | null {
  let u: URL
  try {
    u = new URL(url, 'https://www.youtube.com')
  } catch {
    return null
  }
  if (!u.pathname.endsWith('/api/timedtext')) return null
  const v = u.searchParams.get('v')
  return {
    videoId: v && VIDEO_ID.test(v) ? v : null,
    lang: u.searchParams.get('tlang') || u.searchParams.get('lang') || 'und',
    autoGenerated: u.searchParams.get('kind') === 'asr',
  }
}

