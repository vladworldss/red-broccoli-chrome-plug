/**
 * Sound descriptions in captions — "[Music]", "[SQUEAKING]", "[INAUDIBLE]",
 * "♪" — carry nothing for a concept map. Deliberately narrow: an all-caps
 * word or a known ASR label, standing alone. "A[i]", "[3]" and "(CPU)" stay —
 * lectures about arrays index things in brackets.
 */
const NON_SPEECH = /(?<![\w\]])\[(?:[A-Z][A-Z '-]{2,30}|Music|Applause|Laughter|Inaudible|Silence|Noise)\]|♪+/g
export function stripNonSpeech(text: string): string {
  return normalizeSpace(text.replace(NON_SPEECH, ' '))
}

export type MergeOptions = {
  /** Hard cap on a line's length; ASR captions have no punctuation to split on. */
  maxChars?: number
  /** A pause this long (seconds) always starts a new line. */
  maxGapSec?: number
}

/**
 * Caption fragments → sentence-ish lines, each keeping the start time of its
 * first fragment. Splits on sentence punctuation, on long pauses, and on
 * `maxChars` (the only signal ASR captions give).
 */
export function mergeIntoLines(
  segments: readonly Segment[],
  { maxChars = 280, maxGapSec = 4 }: MergeOptions = {},
): { start: number; text: string }[] {
  const out: { start: number; text: string }[] = []
  let cur: { start: number; text: string; end: number } | null = null

  const flush = () => {
    if (cur && cur.text) out.push({ start: cur.start, text: cur.text })
    cur = null
  }

  for (const seg of segments) {
    const text = stripNonSpeech(seg.text)
    if (!text) continue
    if (cur !== null) {
      const c: { start: number; text: string; end: number } = cur
      const gap = seg.start - c.end
      if (gap > maxGapSec || c.text.length + 1 + text.length > maxChars) flush()
    }
    if (cur === null) {
      cur = { start: seg.start, text, end: seg.start + seg.dur }
    } else {
      const c: { start: number; text: string; end: number } = cur
      c.text = `${c.text} ${text}`
      c.end = Math.max(c.end, seg.start + seg.dur)
    }
    if (/[.!?…。！？]["')\]]?$/.test(text)) flush()
  }
  flush()
  return out
}

/**
 * Chapters from a video description: lines starting with a timestamp. YouTube
 * only treats them as chapters when the first is 0:00 and there are at least
 * three, so the same rule applies here — otherwise a stray "see 3:15" in the
 * description would invent a chapter.
 */
export function parseChapters(description: string): Chapter[] {
  const re = /^\s*[[(]?((?:\d{1,2}:)?\d{1,2}:\d{2})[\])]?\s*[-–—:|]?\s*(.+?)\s*$/
  const chapters: Chapter[] = []
  for (const line of description.split(/\r?\n/)) {
    const m = re.exec(line)
    if (!m) continue
    const start = parseTimestamp(m[1] ?? '')
    if (start === null) continue
    chapters.push({ start, title: m[2] ?? '' })
  }
  if (chapters.length < 3 || chapters[0]!.start !== 0) return []
  for (let i = 1; i < chapters.length; i++) {
    if (chapters[i]!.start <= chapters[i - 1]!.start) return []
  }
  return chapters
}

