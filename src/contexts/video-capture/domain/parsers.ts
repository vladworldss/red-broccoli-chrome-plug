/**
 * Defensive read of the player response object. Every field is optional on
 * YouTube's side (ads, premieres, age-gated videos), so anything missing falls
 * back to an empty value instead of throwing.
 */
export function parsePlayerResponse(raw: unknown): VideoMeta | null {
  if (!isRecord(raw)) return null
  const details = isRecord(raw.videoDetails) ? raw.videoDetails : null
  const videoId = details && typeof details.videoId === 'string' ? details.videoId : null
  if (!videoId || !VIDEO_ID.test(videoId)) return null

  const captions = isRecord(raw.captions) ? raw.captions : null
  const tracklist =
    captions && isRecord(captions.playerCaptionsTracklistRenderer)
      ? captions.playerCaptionsTracklistRenderer
      : null
  const rawTracks = tracklist && Array.isArray(tracklist.captionTracks) ? tracklist.captionTracks : []

  const captionTracks: CaptionTrack[] = rawTracks.filter(isRecord).flatMap((t) => {
    if (typeof t.languageCode !== 'string') return []
    return [
      {
        languageCode: t.languageCode,
        name: textOf(t.name) || t.languageCode,
        autoGenerated: t.kind === 'asr',
      },
    ]
  })

  return {
    videoId,
    title: str(details?.title),
    channel: str(details?.author),
    durationSec: Number(details?.lengthSeconds) || 0,
    chapters: parseChapters(str(details?.shortDescription)),
    captionTracks,
  }
}

/**
 * Pick the track to ask the player for: the first preferred language that
 * exists, then the SPOKEN language (the auto-generated track's language is the
 * best signal for it), then the first human-made track. Within a language,
 * human-made beats auto-generated.
 */
export function chooseCaptionTrack(
  tracks: readonly CaptionTrack[],
  preferredLangs: readonly string[],
): CaptionTrack | null {
  if (tracks.length === 0) return null
  const base = (code: string) => code.toLowerCase().split('-')[0]
  const spoken = tracks.find((t) => t.autoGenerated)?.languageCode
  for (const pref of spoken ? [...preferredLangs, spoken] : preferredLangs) {
    const same = tracks.filter((t) => base(t.languageCode) === base(pref))
    const human = same.find((t) => !t.autoGenerated)
    if (human) return human
    if (same[0]) return same[0]
  }
  return tracks.find((t) => !t.autoGenerated) ?? tracks[0] ?? null
}

