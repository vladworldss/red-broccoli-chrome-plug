const NAMED: Record<string, string> = {
  amp: '&',
  lt: '<',
  gt: '>',
  quot: '"',
  apos: "'",
  nbsp: ' ',
}

/**
 * Decodes XML/HTML entities. Runs twice because legacy srv1 bodies are
 * double-encoded ("&amp;#39;" for an apostrophe).
 */
export function decodeEntities(text: string): string {
  const once = (s: string) =>
    s.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (whole, code: string) => {
      if (code[0] === '#') {
        const n = code[1] === 'x' || code[1] === 'X' ? parseInt(code.slice(2), 16) : Number(code.slice(1))
        return Number.isFinite(n) && n > 0 && n <= 0x10ffff ? String.fromCodePoint(n) : whole
      }
      return NAMED[code.toLowerCase()] ?? whole
    })
  return once(once(text))
}

function cleanXmlText(inner: string): string {
  return normalizeSpace(decodeEntities(inner.replace(/<[^>]+>/g, '')))
}

function parseAttrs(src: string): Record<string, string> {
  const out: Record<string, string> = {}
  for (const m of src.matchAll(/([\w:-]+)\s*=\s*"([^"]*)"/g)) {
    if (m[1]) out[m[1]] = m[2] ?? ''
  }
  return out
}

function withInferredDurations(rows: { start: number; text: string }[]): Segment[] {
  return rows.map((r, i) => {
    const next = rows[i + 1]
    return { start: r.start, dur: next ? Math.max(0, next.start - r.start) : 0, text: r.text }
  })
}

function normalizeSpace(s: string): string {
  return s.replace(/\s+/g, ' ').trim()
}

function num(v: unknown): number {
  const n = typeof v === 'number' ? v : Number(v)
  return Number.isFinite(n) ? n : 0
}

function str(v: unknown): string {
  return typeof v === 'string' ? v : ''
}

/** YouTube text objects come as `{simpleText}` or `{runs:[{text}]}`. */
function textOf(v: unknown): string {
  if (!isRecord(v)) return ''
  if (typeof v.simpleText === 'string') return v.simpleText
  if (Array.isArray(v.runs)) {
    return v.runs.map((r) => (isRecord(r) && typeof r.text === 'string' ? r.text : '')).join('')
  }
  return ''
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}
