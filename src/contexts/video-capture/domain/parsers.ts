/**
 * json3 (`fmt=json3`): `{events:[{tStartMs,dDurationMs,segs:[{utf8}]}]}`.
 * ASR tracks interleave "append" events holding only "\n" — those carry no
 * text and are dropped, as are window/style events without `segs`.
 */
export function parseJson3(body: string): Segment[] {
  let data: unknown
  try {
    data = JSON.parse(body)
  } catch {
    return []
  }
  const events = isRecord(data) && Array.isArray(data.events) ? data.events : []
  const out: Segment[] = []
  for (const ev of events) {
    if (!isRecord(ev) || !Array.isArray(ev.segs)) continue
    const text = normalizeSpace(
      ev.segs.map((s) => (isRecord(s) && typeof s.utf8 === 'string' ? s.utf8 : '')).join(''),
    )
    if (!text) continue
    const start = num(ev.tStartMs) / 1000
    const dur = num(ev.dDurationMs) / 1000
    out.push({ start, dur, text })
  }
  return out
}

/**
 * Both XML flavours YouTube serves:
 *  - srv1 / legacy: `<text start="1.2" dur="3.4">…</text>` (seconds)
 *  - srv3 (`format="3"`): `<p t="1200" d="3400">…<s>…</s></p>` (milliseconds)
 */
export function parseTimedTextXml(body: string): Segment[] {
  const out: Segment[] = []
  const legacy = /<text\b([^>]*)>([\s\S]*?)<\/text>/g
  let m: RegExpExecArray | null
  while ((m = legacy.exec(body))) {
    const attrs = parseAttrs(m[1] ?? '')
    const text = cleanXmlText(m[2] ?? '')
    if (!text) continue
    out.push({ start: num(attrs.start), dur: num(attrs.dur), text })
  }
  if (out.length > 0) return out

  const srv3 = /<p\b([^>]*)>([\s\S]*?)<\/p>/g
  while ((m = srv3.exec(body))) {
    const attrs = parseAttrs(m[1] ?? '')
    const text = cleanXmlText(m[2] ?? '')
    if (!text) continue
    out.push({ start: num(attrs.t) / 1000, dur: num(attrs.d) / 1000, text })
  }
  return out
}

/** Sniffs the body format; the URL's `fmt` param is not always present. */
export function parseTimedTextBody(body: string): Segment[] {
  const trimmed = body.trimStart()
  if (trimmed.startsWith('{')) return parseJson3(trimmed)
  if (trimmed.startsWith('<')) return parseTimedTextXml(trimmed)
  return []
}

/**
 * Rows scraped from YouTube's "Show transcript" panel: a visible timestamp
 * string plus text. Durations are inferred from the next row's start.
 */
export function parseTranscriptRows(
  rows: ReadonlyArray<{ timestamp: string; text: string }>,
): Segment[] {
  const timed = rows
    .map((r) => ({ start: parseTimestamp(r.timestamp), text: normalizeSpace(r.text) }))
    .filter((r): r is { start: number; text: string } => r.start !== null && r.text !== '')
  return withInferredDurations(timed)
}

/**
 * Free text the user pasted. Understands the shapes people actually paste:
 *  - YouTube's transcript panel copied as-is: a timestamp line, then text lines
 *  - "0:12 text" / "[0:12] text" / "(0:12) text" on one line
 *  - a subtitle file: SRT or WebVTT (e.g. the one RedBroccoli itself saves)
 *  - plain prose with no timestamps at all → `timed: false`
 */
export function parseManualTranscript(input: string): { segments: Segment[]; timed: boolean } {
  const cues = parseCueFile(input)
  if (cues.length > 0) return { timed: true, segments: cues }

  const lines = input.split(/\r?\n/).map((l) => l.trim()).filter(Boolean)
  const inline = /^[[(]?((?:\d{1,2}:)?\d{1,2}:\d{2})[\])]?\s*[-–—:]?\s*(.*)$/

  const rows: { start: number; text: string }[] = []
  let pendingStart: number | null = null
  let sawTimestamp = false
  for (const line of lines) {
    const m = inline.exec(line)
    const start = m ? parseTimestamp(m[1] ?? '') : null
    if (m && start !== null) {
      sawTimestamp = true
      const rest = normalizeSpace(m[2] ?? '')
      if (rest) {
        rows.push({ start, text: rest })
        pendingStart = null
      } else {
        pendingStart = start
      }
      continue
    }
    if (pendingStart !== null) {
      rows.push({ start: pendingStart, text: line })
      pendingStart = null
    } else if (rows.length > 0 && sawTimestamp) {
      // Continuation of the previous timestamped row.
      const last = rows[rows.length - 1]!
      last.text = `${last.text} ${line}`
    } else {
      rows.push({ start: 0, text: line })
    }
  }

  if (!sawTimestamp) {
    return {
      timed: false,
      segments: rows.map((r) => ({ start: 0, dur: 0, text: normalizeSpace(r.text) })),
    }
  }
  return { timed: true, segments: withInferredDurations(rows.filter((r) => r.text)) }
}

const CUE_TIMING = /^(?:\d+\s+)?((?:\d+:)?\d{1,2}:\d{2}[.,]\d{1,3})\s*-->\s*((?:\d+:)?\d{1,2}:\d{2}[.,]\d{1,3})/

/**
 * SRT / WebVTT: blocks of an optional cue number, a "start --> end" line and
 * text lines. Without this, a pasted .srt reached the model with every
 * "00:02:30,000 --> 00:02:40,000" and cue number inside the text (~25% junk).
 * YouTube's own VTT repeats the previous line at the top of each cue (rolling
 * captions); a line equal to the one just kept is dropped. Empty = not a cue file.
 */
export function parseCueFile(input: string): Segment[] {
  const lines = input.split(/\r?\n/)
  const out: Segment[] = []
  let lastLine = ''
  for (let i = 0; i < lines.length; i++) {
    const m = CUE_TIMING.exec(lines[i]!.trim())
    if (!m) continue
    const start = cueSeconds(m[1]!)
    const end = cueSeconds(m[2]!)
    const text: string[] = []
    for (i++; i < lines.length && lines[i]!.trim() !== ''; i++) {
      const line = normalizeSpace(lines[i]!.replace(/<[^>]*>/g, '')) // VTT inline tags / word timings
      if (CUE_TIMING.exec(line)) {
        i--
        break
      }
      if (line && line !== lastLine) text.push(line)
      if (line) lastLine = line
    }
    if (text.length > 0) out.push({ start, dur: Math.max(0, end - start), text: decodeEntities(text.join(' ')) })
  }
  return out
}

function cueSeconds(stamp: string): number {
  const parts = stamp.replace(',', '.').split(':').map(Number)
  return parts.reduce((acc, p) => acc * 60 + p, 0)
}

