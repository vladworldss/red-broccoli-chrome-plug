export type PromptContext = {
  title: string
  /** "auto" → write in the lecture's own language; otherwise a language name. */
  outputLanguage: string
  timed: boolean
  autoGeneratedCaptions?: boolean
  chapters?: readonly { title: string; start: number }[]
}

function languageRule(outputLanguage: string): string {
  return outputLanguage === 'auto' || !outputLanguage.trim()
    ? 'Write terms, definitions and summaries in the language of the lecture.'
    : `Write terms, definitions and summaries in ${outputLanguage.trim()}. Keep a well-known original-language term as an alias.`
}

export const EXTRACTION_SYSTEM = `You build study concept maps for students from lecture transcripts.
Your job is to find the KEY CONCEPTS a student must learn from the lecture — not to summarize it.

A concept is a term, method, theorem, rule, formula, or named idea from the subject.
Do NOT include: course logistics, jokes, filler, people (unless a concept is named after them), one-off examples that are not concepts themselves.

For each concept:
- term: the canonical name used in the field, singular, without articles, capitalized as in a textbook glossary ("Derivative", "Chain rule", "Taylor series"). Auto-generated captions mishear technical words — correct them from context (e.g. "the rivative" → "derivative").
- definition: one sentence (max 25 words) saying what it is, grounded in how THIS lecture explains it.
- aliases: other names, abbreviations or notation actually used for it (e.g. "f'(x)", "dy/dx"). Empty array if none.
- t: lines are prefixed with a number in brackets — the second at which that line starts. Copy the number of the line where the concept is first EXPLAINED (not merely mentioned). Use null if lines have no bracketed numbers.
- importance: 0..1. 1 = central idea of the lecture, 0.5 = supporting concept, 0.2 = briefly mentioned.
- summary: 1–3 short sentences in PLAIN words for a first-year student: what it is and why it matters, as this lecture explains it. Explain any jargon you use; add an everyday analogy when it helps. Do not just repeat the definition.
- refTitle: the exact title of the English Wikipedia article about this concept (e.g. "Big O notation", not "Big O"; "Derivative" for "производная"). Empty string if no article fits.

topic: a short name of the subject area (e.g. "Calculus: derivatives").
field: the subject area of the whole lecture — math, cs, physics, chemistry, biology, economics, or other.
Return between 5 and 40 concepts, more for longer and denser lectures. Never invent concepts that are not in the transcript.`

export function extractionPrompt(
  ctx: PromptContext,
  lines: readonly TranscriptLine[],
  part: { index: number; total: number },
): string {
  const header = [
    `Lecture title: ${ctx.title || '(unknown)'}`,
    languageRule(ctx.outputLanguage),
    ctx.autoGeneratedCaptions ? 'The transcript comes from auto-generated captions: expect misheard words.' : '',
    ctx.chapters?.length
      ? `Chapters:\n${ctx.chapters.map((c) => `[${Math.floor(c.start)}] ${c.title}`).join('\n')}`
      : '',
    part.total > 1
      ? `This is part ${part.index + 1} of ${part.total} of the transcript. Extract concepts from this part only.`
      : '',
  ].filter(Boolean)
  return `${header.join('\n')}\n\nTranscript:\n${renderLines(lines, ctx.timed)}`
}

export const RELATIONS_SYSTEM = `You organize the concepts of a lecture into a study map.
Given a list of concepts, return typed relations between them:
- "A part-of B": A is a subtopic, component, special case, or kind of B (e.g. "chain rule" part-of "differentiation rule", "linear regression" part-of "regression"). This builds the hierarchy: give each concept AT MOST ONE part-of parent, and leave the broadest topics without one.
- "A requires B": to understand A a student must first know B (e.g. "derivative" requires "limit").

Use the terms EXACTLY as listed. Only relate concepts from the list. Do not create cycles. Prefer fewer, confident relations over many weak ones.`

export function relationsPrompt(
  ctx: Pick<PromptContext, 'title' | 'outputLanguage'>,
  topic: string,
  concepts: readonly { term: string; definition: string }[],
): string {
  return [
    `Lecture title: ${ctx.title || '(unknown)'}`,
    `Topic: ${topic || '(unknown)'}`,
    '',
    'Concepts:',
    ...concepts.map((c) => `- ${c.term}: ${c.definition}`),
  ].join('\n')
}
