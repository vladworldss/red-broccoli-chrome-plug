import type { LlmPort } from '../../llm-gateway'
import {
  chunkLines,
  createConceptMap,
  mergeConcepts,
  validateExtraction,
  validateRelations,
  type ConceptMap,
  type RawConcept,
  type Relation,
  type TranscriptLine,
} from '../domain'
import type { ConceptMapCache } from './ConceptMapCache'
import {
  EXTRACTION_SCHEMA,
  EXTRACTION_SYSTEM,
  PROMPT_VERSION,
  RELATIONS_SCHEMA,
  RELATIONS_SYSTEM,
  extractionPrompt,
  relationsPrompt,
} from './prompts'

export type BuildConceptMapInput = {
  videoId: string
  title: string
  lang: string
  durationSec?: number
  lines: readonly TranscriptLine[]
  timed: boolean
  autoGeneratedCaptions?: boolean
  chapters?: readonly { title: string; start: number }[]
  /** "auto" or a language name, e.g. "English". */
  outputLanguage: string
  /** Bypass the cache read ("Rebuild"). The new map still replaces the old. */
  force?: boolean
}

export type BuildProgress =
  | { step: 'extract'; current: number; total: number }
  | { step: 'relate' }

export type BuildConceptMapDeps = {
  llm: LlmPort
  cache?: ConceptMapCache
  clock?: () => string
  onProgress?: (p: BuildProgress) => void
  signal?: AbortSignal
  /** Per-chunk character budget. ~120k chars ≈ 30k tokens: one chunk for most lectures. */
  maxChunkChars?: number
}

export type BuildConceptMapResult = { map: ConceptMap; fromCache: boolean }

export class EmptyTranscriptError extends Error {
  constructor() {
    super('The transcript is empty')
    this.name = 'EmptyTranscriptError'
  }
}

export class NoConceptsError extends Error {
  constructor() {
    super('No concepts were found in this transcript')
    this.name = 'NoConceptsError'
  }
}

/** Relating more than this many concepts costs tokens without improving the tree. */
const MAX_CONCEPTS_TO_RELATE = 80

/**
 * Pipeline: cache → chunk → extract (per chunk) → merge → relate → map → cache.
 *
 * The relate step is best-effort: if it fails with a schema problem the map is
 * still returned as a flat list of concepts rather than losing the whole run.
 * Transport/auth errors still propagate — those need the user's attention.
 */
export async function buildConceptMap(
  input: BuildConceptMapInput,
  deps: BuildConceptMapDeps,
): Promise<BuildConceptMapResult> {
  const key = {
    videoId: input.videoId,
    lang: input.lang,
    promptVersion: PROMPT_VERSION,
    model: deps.llm.modelId,
  }

  if (deps.cache && !input.force) {
    const cached = await deps.cache.get(key).catch(() => null)
    if (cached) return { map: cached, fromCache: true }
  }

  const lines = input.lines.filter((l) => l.text.trim().length > 0)
  if (lines.length === 0) throw new EmptyTranscriptError()

  const ctx = {
    title: input.title,
    outputLanguage: input.outputLanguage,
    timed: input.timed,
    ...(input.autoGeneratedCaptions !== undefined ? { autoGeneratedCaptions: input.autoGeneratedCaptions } : {}),
    ...(input.chapters ? { chapters: input.chapters } : {}),
  }

  const chunks = chunkLines(lines, deps.maxChunkChars ?? 120_000, input.timed)
  const raws: RawConcept[] = []
  let topic = ''
  for (let i = 0; i < chunks.length; i++) {
    deps.onProgress?.({ step: 'extract', current: i + 1, total: chunks.length })
    const raw = await deps.llm.generateJson({
      system: EXTRACTION_SYSTEM,
      prompt: extractionPrompt(ctx, chunks[i]!, { index: i, total: chunks.length }),
      schema: EXTRACTION_SCHEMA,
      ...(deps.signal ? { signal: deps.signal } : {}),
    })
    const extraction = validateExtraction(
      raw,
      input.durationSec !== undefined ? { durationSec: input.durationSec } : {},
    )
    if (!topic && extraction.topic) topic = extraction.topic
    raws.push(...extraction.concepts)
  }

  const concepts = mergeConcepts(raws)
  if (concepts.length === 0) throw new NoConceptsError()

  let relations: Relation[] = []
  if (concepts.length >= 2) {
    deps.onProgress?.({ step: 'relate' })
    const toRelate = [...concepts]
      .sort((a, b) => b.importance - a.importance)
      .slice(0, MAX_CONCEPTS_TO_RELATE)
    try {
      const raw = await deps.llm.generateJson({
        system: RELATIONS_SYSTEM,
        prompt: relationsPrompt(ctx, topic, toRelate),
        schema: RELATIONS_SCHEMA,
        ...(deps.signal ? { signal: deps.signal } : {}),
      })
      relations = validateRelations(raw, concepts)
    } catch (err) {
      if (!isSchemaProblem(err)) throw err
    }
  }

  const map = createConceptMap({
    ...key,
    title: input.title,
    topic,
    createdAt: (deps.clock ?? (() => new Date().toISOString()))(),
    timed: input.timed,
    concepts,
    relations,
  })

  if (deps.cache) await deps.cache.put(map).catch(() => {})
  return { map, fromCache: false }
}

/** Cache lookup for the panel's "open a video" path — never calls the LLM. */
export async function loadCachedConceptMap(
  videoId: string,
  deps: { cache: ConceptMapCache; model: string },
): Promise<ConceptMap | null> {
  return deps.cache.findLatest(videoId, PROMPT_VERSION, deps.model).catch(() => null)
}

/**
 * What to show when a build fails: the map for the current prompt version and
 * model if one is cached, otherwise the newest map of ANY version. Null when
 * the video has never had a map.
 */
export async function loadFallbackConceptMap(
  videoId: string,
  deps: { cache: ConceptMapCache; model: string },
): Promise<ConceptMap | null> {
  const current = await loadCachedConceptMap(videoId, deps)
  if (current) return current
  return deps.cache.findLatestAny(videoId).catch(() => null)
}

/** True when a map was built with another model or prompt version than now. */
export function isOutdatedMap(map: ConceptMap, model: string): boolean {
  return map.promptVersion !== PROMPT_VERSION || map.model !== model
}

function isSchemaProblem(err: unknown): boolean {
  if (typeof err !== 'object' || err === null) return false
  const e = err as { name?: unknown; kind?: unknown }
  return e.name === 'ExtractionSchemaError' || e.kind === 'schema'
}
