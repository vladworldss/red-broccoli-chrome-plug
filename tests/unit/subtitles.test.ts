import { describe, expect, it } from 'vitest'

import {
  parseJson3,
  parseManualTranscript,
  subtitleFileName,
  toSrt,
  toTimestampedText,
  type Transcript,
} from '../../src/contexts/video-capture/domain'
import { fixture } from './helpers/fixtures'

const VID = 'ZA-tUyM_y7s'

function transcript(segments: Transcript['segments'], over: Partial<Transcript> = {}): Transcript {
  return { videoId: VID, lang: 'en', autoGenerated: false, timed: true, source: 'intercept', segments, ...over }
}

describe('toSrt', () => {
  it('numbers cues and formats HH:MM:SS,mmm', () => {
    const srt = toSrt(transcript([
      { start: 1.2, dur: 3.1, text: 'today we talk' },
      { start: 3725.4, dur: 2, text: 'an hour later' },
    ]))
    expect(srt).toBe(
      ['1', '00:00:01,200 --> 00:00:04,300', 'today we talk', '', '2', '01:02:05,400 --> 01:02:07,400', 'an hour later', ''].join('\n'),
    )
  })

  it('clamps overlapping ASR cues to the next start; dur 0 runs to the next cue', () => {
    const srt = toSrt(transcript([
      { start: 0, dur: 10, text: 'a' }, // overlaps b
      { start: 4, dur: 0, text: 'b' }, // no duration (DOM/paste)
      { start: 9, dur: 0, text: 'c' }, // last, no duration → fallback
      { start: 20, dur: 1, text: '   ' }, // blank cue dropped
    ]))!
    expect(srt).toContain('00:00:00,000 --> 00:00:04,000')
    expect(srt).toContain('00:00:04,000 --> 00:00:09,000')
    expect(srt).toContain('00:00:09,000 --> 00:00:12,000')
    expect(srt.match(/-->/g)).toHaveLength(3)
  })

  it('end is always after start, even for duplicated start times', () => {
    const srt = toSrt(transcript([
      { start: 5, dur: 0, text: 'x' },
      { start: 5, dur: 0, text: 'y' },
    ]))!
    expect(srt).toContain('00:00:05,000 --> 00:00:05,500')
  })

  it('untimed transcript → null', () => {
    expect(toSrt(transcript([{ start: 0, dur: 0, text: 'prose' }], { timed: false }))).toBeNull()
  })

  it('works on a real json3 capture', () => {
    const srt = toSrt(transcript(parseJson3(fixture('timedtext-json3.json'))))!
    expect(srt.split('\n\n')).toHaveLength(3)
    expect(srt).toContain('00:12:14,000 --> 00:12:19,200')
  })
})

describe('toTimestampedText', () => {
  it('round-trips through the paste box parser', () => {
    const t = transcript([
      { start: 0, dur: 2, text: 'A limit is' },
      { start: 2, dur: 2, text: 'where it goes.' },
      { start: 734, dur: 3, text: 'The derivative.' },
    ])
    const txt = toTimestampedText(t)
    expect(txt).toBe('0:00 A limit is where it goes.\n12:14 The derivative.\n')
    const back = parseManualTranscript(txt)
    expect(back.timed).toBe(true)
    expect(back.segments.map((s) => [s.start, s.text])).toEqual([
      [0, 'A limit is where it goes.'],
      [734, 'The derivative.'],
    ])
  })

  it('untimed transcript → paragraphs', () => {
    expect(toTimestampedText(transcript([{ start: 0, dur: 0, text: 'one' }, { start: 0, dur: 0, text: 'two' }], { timed: false }))).toBe(
      'one\n\ntwo\n',
    )
  })
})

describe('subtitleFileName', () => {
  it('keeps the title, adds id and language', () => {
    expect(subtitleFileName('1. Algorithms and Computation', VID, 'en', 'srt')).toBe(
      '1. Algorithms and Computation [ZA-tUyM_y7s].en.srt',
    )
  })

  it('drops characters illegal in file names; omits unknown language; caps length', () => {
    expect(subtitleFileName('Lecture 3: A/B "tests" <live>?', VID, 'und', 'txt')).toBe('Lecture 3 A B tests live [ZA-tUyM_y7s].txt')
    expect(subtitleFileName('', VID, 'ru', 'srt')).toBe('ZA-tUyM_y7s.ru.srt')
    expect(subtitleFileName('x'.repeat(300), VID, 'en', 'srt').length).toBeLessThan(110)
  })
})
