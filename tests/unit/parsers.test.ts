describe('parseManualTranscript', () => {
  it('YouTube panel copy-paste: timestamp line, then text line(s)', () => {
    const { segments, timed } = parseManualTranscript('0:00\nToday we talk\nabout limits\n0:04\nA limit is…\n')
    expect(timed).toBe(true)
    expect(segments).toEqual([
      { start: 0, dur: 4, text: 'Today we talk about limits' },
      { start: 4, dur: 0, text: 'A limit is…' },
    ])
  })

  it('inline "[0:12] text" and "0:12 - text"', () => {
    const { segments } = parseManualTranscript('[0:12] first\n1:02:05 - second')
    expect(segments.map((s) => [s.start, s.text])).toEqual([
      [12, 'first'],
      [3725, 'second'],
    ])
  })

  it('plain prose → untimed', () => {
    const { segments, timed } = parseManualTranscript('Limits are…\n\nDerivatives are…')
    expect(timed).toBe(false)
    expect(segments.map((s) => s.text)).toEqual(['Limits are…', 'Derivatives are…'])
    expect(segments.every((s) => s.start === 0)).toBe(true)
  })
})

describe('mergeIntoLines', () => {
  const seg = (start: number, text: string, dur = 1) => ({ start, dur, text })

  it('joins fragments until sentence punctuation', () => {
    expect(mergeIntoLines([seg(0, 'A limit is'), seg(1, 'where it goes.'), seg(2, 'Next')])).toEqual([
      { start: 0, text: 'A limit is where it goes.' },
      { start: 2, text: 'Next' },
    ])
  })

  it('splits ASR text (no punctuation) by length', () => {
    const lines = mergeIntoLines(
      Array.from({ length: 30 }, (_, i) => seg(i, 'word word word')),
      { maxChars: 50 },
    )
    expect(lines.length).toBeGreaterThan(5)
    expect(lines.every((l) => l.text.length <= 50)).toBe(true)
    expect(lines[1]!.start).toBeGreaterThan(0)
  })

  it('a long pause starts a new line', () => {
    expect(mergeIntoLines([seg(0, 'before'), seg(30, 'after')])).toHaveLength(2)
  })
})

describe('parseChapters', () => {
  it('requires ≥3 entries starting at 0:00, ascending', () => {
    expect(parseChapters('0:00 Intro\n2:30 - Limits\n12:14 Derivative')).toEqual([
      { start: 0, title: 'Intro' },
      { start: 150, title: 'Limits' },
      { start: 734, title: 'Derivative' },
    ])
    expect(parseChapters('see 3:15 and 4:00 and 5:00')).toEqual([])
    expect(parseChapters('1:00 a\n2:00 b\n3:00 c')).toEqual([]) // no 0:00
    expect(parseChapters('0:00 a\n5:00 b\n2:00 c')).toEqual([]) // not ascending
  })
})

describe('parsePlayerResponse / chooseCaptionTrack', () => {
  const meta = parsePlayerResponse(JSON.parse(fixture('player-response.json')))

  it('reads details, chapters (ignoring the stray timestamp) and tracks', () => {
    expect(meta).toMatchObject({
      videoId: 'dQw4w9WgXcQ',
      title: 'Calculus 1: Limits and Derivatives',
      channel: 'Math Lectures',
      durationSec: 3725,
    })
    expect(meta!.chapters.map((c) => c.title)).toEqual(['Intro', 'Limits', 'Derivative', 'Applications'])
    expect(meta!.captionTracks).toEqual([
      { languageCode: 'de', name: 'German', autoGenerated: false },
      { languageCode: 'en', name: 'English (auto-generated)', autoGenerated: true },
      { languageCode: 'en', name: 'English', autoGenerated: false },
    ])
  })

  it('returns null for junk', () => {
    expect(parsePlayerResponse(null)).toBeNull()
    expect(parsePlayerResponse({ videoDetails: { videoId: 'nope' } })).toBeNull()
  })

  it('prefers the spoken language (from the ASR track), human-made over ASR', () => {
    expect(chooseCaptionTrack(meta!.captionTracks, [])).toEqual({
      languageCode: 'en',
      name: 'English',
      autoGenerated: false,
    })
  })

  it('an explicit preference wins; region subtags match the base language', () => {
    expect(chooseCaptionTrack(meta!.captionTracks, ['de-AT'])?.languageCode).toBe('de')
  })

  it('no tracks → null', () => {
    expect(chooseCaptionTrack([], ['en'])).toBeNull()
  })
})
