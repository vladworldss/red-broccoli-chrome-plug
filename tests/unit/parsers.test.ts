describe('timestamps', () => {
  it('formats m:ss and h:mm:ss', () => {
    expect(formatTimestamp(0)).toBe('0:00')
    expect(formatTimestamp(734.9)).toBe('12:14')
    expect(formatTimestamp(3725)).toBe('1:02:05')
    expect(formatTimestamp(-5)).toBe('0:00')
    expect(formatTimestamp(Number.NaN)).toBe('0:00')
  })

  it('parses only well-formed timestamps', () => {
    expect(parseTimestamp('12:14')).toBe(734)
    expect(parseTimestamp(' 1:02:05 ')).toBe(3725)
    expect(parseTimestamp('0:07')).toBe(7)
    expect(parseTimestamp('12')).toBeNull()
    expect(parseTimestamp('1:75')).toBeNull()
    expect(parseTimestamp('a:bc')).toBeNull()
  })
})

describe('videoIdFromUrl', () => {
  it.each([
    ['https://www.youtube.com/watch?v=dQw4w9WgXcQ&t=10s', 'dQw4w9WgXcQ'],
    ['https://m.youtube.com/watch?v=dQw4w9WgXcQ', 'dQw4w9WgXcQ'],
    ['https://youtu.be/dQw4w9WgXcQ?si=x', 'dQw4w9WgXcQ'],
    ['https://www.youtube.com/shorts/dQw4w9WgXcQ', 'dQw4w9WgXcQ'],
    ['https://www.youtube.com/live/dQw4w9WgXcQ', 'dQw4w9WgXcQ'],
    ['https://www.youtube.com/embed/dQw4w9WgXcQ', 'dQw4w9WgXcQ'],
  ])('%s', (url, id) => expect(videoIdFromUrl(url)).toBe(id))

  it.each([
    'https://www.youtube.com/',
    'https://www.youtube.com/results?search_query=calculus',
    'https://www.youtube.com/watch?v=short',
    'https://evil.example/watch?v=dQw4w9WgXcQ',
    'not a url',
  ])('rejects %s', (url) => expect(videoIdFromUrl(url)).toBeNull())
})

describe('timedTextUrlInfo', () => {
  it('reads video, language and ASR flag; tlang wins over lang', () => {
    expect(timedTextUrlInfo('/api/timedtext?v=dQw4w9WgXcQ&lang=en&kind=asr&fmt=json3&pot=xyz')).toEqual({
      videoId: 'dQw4w9WgXcQ',
      lang: 'en',
      autoGenerated: true,
    })
    expect(timedTextUrlInfo('https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=en&tlang=ru')?.lang).toBe('ru')
  })

  it('ignores other endpoints', () => {
    expect(timedTextUrlInfo('https://www.youtube.com/youtubei/v1/player')).toBeNull()
  })
})

describe('caption body parsers', () => {
  it('json3: joins segs, drops ASR newline-only append events and window events', () => {
    const segs = parseJson3(fixture('timedtext-json3.json'))
    expect(segs).toEqual([
      { start: 1.2, dur: 3.1, text: 'today we talk about limits' },
      { start: 4.3, dur: 4, text: 'a limit describes where a function is heading' },
      { start: 734, dur: 5.2, text: 'the derivative is the limit of the difference quotient' },
    ])
  })

  it('json3: garbage in → empty, not a throw', () => {
    expect(parseJson3('not json')).toEqual([])
    expect(parseJson3('{"events": 5}')).toEqual([])
  })

  it('srv1 XML: seconds, double-encoded entities, empty cues dropped, newlines collapsed', () => {
    const segs = parseTimedTextXml(fixture('timedtext-srv1.xml'))
    expect(segs).toEqual([
      { start: 0.5, dur: 2.1, text: "Today we'll talk about limits." },
      { start: 2.6, dur: 3, text: 'A limit & a function <3' },
      { start: 734.2, dur: 4.8, text: 'The derivative is the limit of the difference quotient.' },
    ])
  })

  it('srv3 XML: milliseconds and nested <s> spans', () => {
    expect(parseTimedTextXml(fixture('timedtext-srv3.xml'))).toEqual([
      { start: 1.2, dur: 3.1, text: 'today we talk' },
      { start: 734, dur: 5.2, text: 'derivative & slope' },
    ])
  })

  it('sniffs the format from the body', () => {
    expect(parseTimedTextBody(fixture('timedtext-json3.json'))).toHaveLength(3)
    expect(parseTimedTextBody(fixture('timedtext-srv1.xml'))).toHaveLength(3)
    expect(parseTimedTextBody('')).toEqual([])
  })

  it('decodeEntities handles numeric, hex and named entities', () => {
    expect(decodeEntities('&#39;&#x41;&quot;&nbsp;&bogus;')).toBe(`'A" &bogus;`)
  })
})

