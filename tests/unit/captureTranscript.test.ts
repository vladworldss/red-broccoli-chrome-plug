import { describe, expect, it, vi } from 'vitest'

import {
  captureTranscript,
  manualTranscript,
  transcriptToLines,
  type Transcript,
  type TranscriptCache,
  type TranscriptProvider,
} from '../../src/contexts/video-capture'

const VID = 'dQw4w9WgXcQ'

function transcript(source: Transcript['source'], text = 'hello.'): Transcript {
  return { videoId: VID, lang: 'en', autoGenerated: false, timed: true, source, segments: [{ start: 1, dur: 1, text }] }
}

function provider(name: TranscriptProvider['name'], result: Transcript | null | Error): TranscriptProvider {
  return {
    name,
    get: vi.fn(async () => {
      if (result instanceof Error) throw result
      return result
    }),
  }
}

function memoryCache(initial: Transcript | null = null): TranscriptCache & { stored: Transcript | null } {
  const c = {
    stored: initial,
    get: vi.fn(async () => c.stored),
    put: vi.fn(async (t: Transcript) => {
      c.stored = t
    }),
  }
  return c
}

describe('captureTranscript', () => {
  it('first usable provider wins; later ones are not called', async () => {
    const a = provider('intercept', transcript('intercept'))
    const b = provider('dom', transcript('dom'))
    const res = await captureTranscript({ videoId: VID }, { providers: [a, b] })
    expect(res.transcript?.source).toBe('intercept')
    expect(b.get).not.toHaveBeenCalled()
  })

  it('a throwing or empty provider falls through to the next, and is recorded', async () => {
    const res = await captureTranscript(
      { videoId: VID },
      {
        providers: [
          provider('intercept', new Error('boom')),
          provider('intercept', transcript('intercept', '   ')),
          provider('dom', transcript('dom')),
        ],
      },
    )
    expect(res.transcript?.source).toBe('dom')
    expect(res.attempts).toEqual([
      { provider: 'intercept', outcome: 'error', message: 'boom' },
      { provider: 'intercept', outcome: 'empty' },
      { provider: 'dom', outcome: 'ok' },
    ])
  })

  it('rejects a transcript for a different video (stale capture after navigation)', async () => {
    const other = { ...transcript('intercept'), videoId: 'AAAAAAAAAAA' }
    const res = await captureTranscript({ videoId: VID }, { providers: [provider('intercept', other)] })
    expect(res.transcript).toBeNull()
  })

  it('cache hit skips providers; force bypasses the read but still writes', async () => {
    const cache = memoryCache(transcript('dom'))
    const p = provider('intercept', transcript('intercept'))

    const hit = await captureTranscript({ videoId: VID }, { providers: [p], cache })
    expect(hit.fromCache).toBe(true)
    expect(p.get).not.toHaveBeenCalled()

    const forced = await captureTranscript({ videoId: VID, force: true }, { providers: [p], cache })
    expect(forced.fromCache).toBe(false)
    expect(cache.stored?.source).toBe('intercept')
  })

  it('nothing works → null with every attempt listed', async () => {
    const res = await captureTranscript({ videoId: VID }, { providers: [provider('intercept', null), provider('dom', null)] })
    expect(res.transcript).toBeNull()
    expect(res.attempts.map((a) => a.outcome)).toEqual(['empty', 'empty'])
  })
})

describe('manualTranscript / transcriptToLines', () => {
  it('builds a manual transcript, or null for blank input', () => {
    expect(manualTranscript(VID, '   \n ')).toBeNull()
    const t = manualTranscript(VID, '0:00\nLimits.\n0:10\nDerivatives.')!
    expect(t).toMatchObject({ source: 'manual', timed: true, lang: 'und' })
    expect(transcriptToLines(t)).toEqual([
      { start: 0, text: 'Limits.' },
      { start: 10, text: 'Derivatives.' },
    ])
  })

  it('untimed text keeps its paragraphs', () => {
    const t = manualTranscript(VID, 'First paragraph\nSecond paragraph')!
    expect(t.timed).toBe(false)
    expect(transcriptToLines(t).map((l) => l.text)).toEqual(['First paragraph', 'Second paragraph'])
  })
})
